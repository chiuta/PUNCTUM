(function(){
  const EVS=['click','change','input','keydown'];
  EVS.forEach(function(ev){
    document.addEventListener(ev,function(e){
      for(let el=e.target;el&&el.getAttribute;el=el.parentNode){
        const id=el.getAttribute('data-h-'+ev);
        if(id!==null){
          const a=[];for(let k=0;el.hasAttribute('data-a-'+id+'-'+k);k++)a.push(el.getAttribute('data-a-'+id+'-'+k));
          const r=HND[id].call(el,e,a);
          if(r===false)e.preventDefault();
          if(e.cancelBubble)break;
        }
      }
    });
  });
})();
